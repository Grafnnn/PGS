  function mountSoilVolume(atlas, stage) {
    // PIT-2 planned rectangular envelope, using its decoded XY corners in metres.
    const footprint = [[29.50677000,-1.84087556], [32.50488328,-1.94786000],
                       [32.61182000,1.05026294], [29.61370672,1.15720000]];
    const vertices = [200.000, 203.800].flatMap(z => footprint.map(([x,y]) => [x,y,z]));
    const faces = [[4,5,6,7], [0,1,5,4], [1,2,6,5], [2,3,7,6], [3,0,4,7]];
    const rimId = 'NET-GOL-PD-POS-R12-VIEW-RIM-PIT-2';
    const layer = document.createElement('canvas');
    layer.id = 'pdSoilVolume';
    layer.hidden = true;
    layer.setAttribute('aria-hidden', 'true');
    stage.append(layer);
    const ctx = layer.getContext('2d');
    let enabled = false;
    let frame = 0;

    function draw() {
      frame = 0;
      const hasSection = !!atlas.sectionState()?.section;
      const subset = atlas.visibleSetState();
      layer.hidden = !enabled || !atlas.inScene(rimId) || hasSection ||
        window.__R24.isIsolated() || !!(subset && !subset.ids.includes(rimId));
      if (layer.hidden || !ctx) return;
      const bounds = layer.getBoundingClientRect();
      if (!bounds.width || !bounds.height) return;
      const ratio = Math.min(2, devicePixelRatio || 1);
      const width = Math.round(bounds.width * ratio);
      const height = Math.round(bounds.height * ratio);
      if (layer.width !== width || layer.height !== height) {
        layer.width = width;
        layer.height = height;
      }
      ctx.setTransform(ratio, 0, 0, ratio, 0, 0);
      ctx.clearRect(0, 0, bounds.width, bounds.height);
      const points = vertices.map(world => atlas.projectToScreen(world));
      if (points.some(p => !p || !Number.isFinite(p[0]) || !Number.isFinite(p[1]))) return;
      const xy = points.map(([x,y]) => [x - bounds.left, y - bounds.top]);

      function path(indices) {
        ctx.beginPath();
        ctx.moveTo(...xy[indices[0]]);
        for (const i of indices.slice(1)) ctx.lineTo(...xy[i]);
        ctx.closePath();
      }

      const { az, el } = window.__R24.capture().camera;
      const axis = [Math.cos(el) * Math.cos(az), Math.cos(el) * Math.sin(az), Math.sin(el)];
      const depth = face => face.reduce((sum, i) =>
        sum + vertices[i].reduce((d, x, j) => d + x * axis[j], 0), 0);
      for (const face of [...faces].sort((a,b) => depth(a) - depth(b))) {
        path(face);
        ctx.fillStyle = face === faces[0] ? 'rgba(234,174,74,.29)' : 'rgba(207,133,45,.12)';
        ctx.fill();
        ctx.lineWidth = face === faces[0] ? 2.5 : 1.1;
        ctx.strokeStyle = face === faces[0] ? '#9b521f' : 'rgba(138,75,36,.67)';
        ctx.stroke();
      }

      const cap = xy.slice(4);
      const minX = Math.max(0, Math.min(...cap.map(p => p[0])));
      const maxX = Math.min(bounds.width, Math.max(...cap.map(p => p[0])));
      const minY = Math.max(0, Math.min(...cap.map(p => p[1])));
      const maxY = Math.min(bounds.height, Math.max(...cap.map(p => p[1])));
      ctx.save();
      path(faces[0]);
      ctx.clip();
      ctx.beginPath();
      for (let x = minX - (maxY - minY); x < maxX; x += 9) {
        ctx.moveTo(x, maxY);
        ctx.lineTo(x + maxY - minY, minY);
      }
      ctx.lineWidth = 1;
      ctx.strokeStyle = 'rgba(138,75,36,.55)';
      ctx.stroke();
      ctx.restore();
      ctx.setLineDash([5,4]);
      path([0,1,2,3]);
      ctx.strokeStyle = '#77421e';
      ctx.stroke();
      ctx.setLineDash([]);
    }
    const schedule = () => { if (!frame) frame = requestAnimationFrame(draw); };
    for (const event of ['atlas:camera','atlas:visibility','atlas:section','atlas:sceneready']) {
      document.addEventListener(event, () => { if (enabled) schedule(); });
    }
    new ResizeObserver(() => { if (enabled) schedule(); }).observe(stage);
    return visible => { enabled = visible; schedule(); };
  }

  function addWorldProfile(atlas, stage, panel, links, soilTools) {
    const data = window.ATLAS_PROFILE_WORLD;
    if (!data || !window.ATLAS_PROFILE_OVERLAY) return;

    const trigger = document.createElement('button');
    trigger.type = 'button';
    trigger.id = 'pdWorldProfileToggle';
    trigger.textContent = 'Профиль в 3D';
    trigger.setAttribute('aria-pressed', 'false');
    trigger.setAttribute('aria-controls', 'pdWorldProfileRange');
    links.prepend(trigger);

    const ranges = document.createElement('div');
    ranges.id = 'pdWorldProfileRange';
    ranges.hidden = true;
    ranges.innerHTML = `
      <form aria-label="Интервал профиля в 3D" novalidate>
        <label>Начало, м<input type="text" inputmode="decimal" name="from" value="0" aria-describedby="pdWorldProfileStatus"></label>
        <label>Конец, м<input type="text" inputmode="decimal" name="to" value="400" aria-describedby="pdWorldProfileStatus"></label>
        <button type="submit">Показать</button>
        <button type="button" data-reset>Вся трасса</button>
      </form>
      <p id="pdWorldProfileStatus" role="status"></p>
    `;
    panel.insertBefore(ranges, soilTools);

    const form = ranges.querySelector('form');
    const from = form.elements.namedItem('from');
    const to = form.elements.namedItem('to');
    const message = ranges.querySelector('#pdWorldProfileStatus');
    const sectionLink = links.querySelector('a[href="project/profile-waterline.html"]');
    const overlay = window.ATLAS_PROFILE_OVERLAY.mount(atlas, stage, { getObstacles: () => [panel] });
    const format = new Intl.NumberFormat('ru-RU', { maximumFractionDigits: 3, useGrouping: false });
    let first = 0, last = 400;
    let enabled = false;

    function meters(value) {
      const digits = value?.trim() ?? '';
      return /^\d+(?:[.,]\d{1,3})?$/.test(digits) ? Number(digits.replace(',', '.')) : NaN;
    }
    function onPlan(elevation = window.__R24.capture().camera.el) {
      return Math.abs(elevation - Math.PI / 2) < 1e-4;
    }
    function describe(event) {
      if (!enabled || ranges.dataset.invalid) return;
      const description = onPlan(event?.detail?.el)
        ? 'Переключитесь в 3D, чтобы видеть профиль.'
        : 'Участок ' + format.format(first) + '–' + format.format(last) + ' м от КВ‑1. ≈ расчётная отметка.';
      if (message.textContent !== description) message.textContent = description;
    }
    function fitRange() {
      const points = [overlay.sample(first), ...data.route.filter(point => point.station > first && point.station < last), overlay.sample(last)];
      const levels = points.map(point => point.invert);
      for (const mark of data.marks) {
        if (mark.station >= first && mark.station <= last && Number.isFinite(mark.ground)) levels.push(mark.ground);
      }
      if (first <= data.well.station && data.well.station <= last) levels.push(data.well.beddingBottom);
      const xs = points.map(point => point.x);
      const ys = points.map(point => point.y);
      const lo = [Math.min(...xs)-2, Math.min(...ys)-2, Math.min(...levels)-.8];
      const hi = [Math.max(...xs)+2, Math.max(...ys)+2, Math.max(...levels)+.8];
      const top = Math.ceil(panel.getBoundingClientRect().bottom - stage.getBoundingClientRect().top) + 16;
      atlas.fit([{ bounds: [lo, hi] }], { insets: { top, right: 20, bottom: 72, left: 20 }, pad: 1.15 });
    }
    function setRange(start, end) {
      first = start;
      last = end;
      from.value = format.format(first);
      to.value = format.format(last);
      for (const input of [from, to]) input.removeAttribute('aria-invalid');
      delete ranges.dataset.invalid;
      overlay.setRange(first, last);
      if (sectionLink) {
        const params = new URLSearchParams({ pdFrom: first, pdTo: last });
        sectionLink.href = 'project/profile-waterline.html?' + params;
      }
      describe();
    }
    function show(showProfile) {
      enabled = showProfile;
      ranges.hidden = !enabled;
      document.body.classList.toggle('pdWorldProfileActive', enabled);
      trigger.setAttribute('aria-pressed', String(enabled));
      overlay.setVisible(enabled);
      if (!enabled) return;
      if (onPlan()) document.querySelector('[data-view="iso"]')?.click();
      fitRange();
      describe();
    }

    trigger.addEventListener('click', () => show(!enabled));
    document.addEventListener('atlas:camera', describe);
    form.addEventListener('submit', event => {
      event.preventDefault();
      const start = meters(from.value);
      const end = meters(to.value);
      for (const input of [from, to]) input.removeAttribute('aria-invalid');
      const badField = !Number.isFinite(start) || start > 400 ? from
        : !Number.isFinite(end) || end > 400 || start >= end ? to : null;
      if (badField) {
        ranges.dataset.invalid = 'true';
        badField.setAttribute('aria-invalid', 'true');
        message.textContent = Number.isFinite(start) && Number.isFinite(end) && start <= 400 && end <= 400
          ? 'Конец должен быть больше начала.'
          : 'Введите расстояния от 0 до 400 м.';
        badField.focus();
        return;
      }
      setRange(start, end);
      show(true);
    });
    form.querySelector('[data-reset]').addEventListener('click', () => {
      setRange(0, 400);
      show(true);
    });

    return () => {
      const start = meters(query.get('pdFrom'));
      const end = meters(query.get('pdTo'));
      if (Number.isFinite(start) && Number.isFinite(end) && start < end && end <= 400) setRange(start, end);
      show(true);
    };
  }

